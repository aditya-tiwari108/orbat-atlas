export const weapons = weaponRecords.map((w) => ({
  ...w,
  model: w.model ?? communityModels[w.id],
}));
export const weaponById = Object.fromEntries(weapons.map((w) => [w.id, w]));
export const cartridgeById = Object.fromEntries(
  cartridges.map((c) => [c.id, c]),
);
export function matchWeapon(
  w: Weapon,
  query: string,
  country: string,
  category: string,
) {
  const haystack =
    `${w.name} ${w.subtitle} ${w.description} ${cartridgeById[w.cartridge].name}`
      .toLowerCase()
      .replace(/[^a-z0-9]/g, '');
  return (
    (country === 'all' || w.countries.includes(country as never)) &&
    (category === 'all' || w.category === category) &&
    query
      .toLowerCase()
      .split(/\s+/)
      .every((token) => haystack.includes(token.replace(/[^a-z0-9]/g, '')))
  );
}
